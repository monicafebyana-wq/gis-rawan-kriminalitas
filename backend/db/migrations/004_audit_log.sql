-- Riwayat perubahan data & akun (siapa, kapan, apa). Diisi oleh app/services/audit.py, dibaca lewat GET /api/audit (admin).
CREATE TABLE audit_log (
    id_log       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waktu        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    id_pengguna  INTEGER      REFERENCES pengguna(id_pengguna) ON DELETE SET NULL,   -- akun dihapus -> baris log tetap ada
    username     VARCHAR(50)  NOT NULL,                                              -- salinan, supaya tetap terbaca setelah akun dihapus
    aksi         VARCHAR(30)  NOT NULL,                                              -- tambah / ubah / hapus / impor / ...
    entitas      VARCHAR(30)  NOT NULL,                                              -- kasus / pengguna / polsek / jenis / poligon
    id_entitas   VARCHAR(50),
    detail       JSONB
);
COMMENT ON TABLE audit_log IS 'Riwayat perubahan data oleh pengguna login (tidak pernah memuat password)';
CREATE INDEX idx_audit_waktu   ON audit_log (waktu DESC);
CREATE INDEX idx_audit_entitas ON audit_log (entitas, id_entitas);
