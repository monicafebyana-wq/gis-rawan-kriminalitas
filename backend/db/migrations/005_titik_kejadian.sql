-- 005_titik_kejadian.sql
-- Titik kejadian (koordinat per kejadian) khusus untuk heatmap. TERPISAH dari kasus_kejahatan (rekap per Polsek x jenis x tahun):
-- tabel ini TIDAK mempengaruhi jumlah kasus maupun zona kerawanan.
CREATE TABLE titik_kejadian (
    id_titik     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_polsek    INTEGER  REFERENCES polsek(id_polsek) ON UPDATE CASCADE ON DELETE SET NULL,   -- otomatis dari poligon; NULL bila titik di luar semua wilayah
    id_jenis     INTEGER  NOT NULL REFERENCES jenis_kejahatan(id_jenis) ON UPDATE CASCADE ON DELETE RESTRICT,
    tanggal      DATE     NOT NULL CHECK (tanggal BETWEEN DATE '2000-01-01' AND DATE '2100-12-31'),
    geom         geometry(Point, 4326) NOT NULL,                                             -- WGS 84: ST_MakePoint(lng, lat)
    dibuat_pada  TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE titik_kejadian IS 'Titik kejadian untuk heatmap (lat/lng persis). Bukan sumber angka kasus/zona.';
CREATE INDEX idx_titik_geom    ON titik_kejadian USING GIST (geom);
CREATE INDEX idx_titik_tanggal ON titik_kejadian (tanggal);
CREATE INDEX idx_titik_jenis   ON titik_kejadian (id_jenis);
CREATE INDEX idx_titik_polsek  ON titik_kejadian (id_polsek);
