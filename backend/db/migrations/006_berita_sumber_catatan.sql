-- 006_berita_sumber_catatan.sql
-- 1) titik_kejadian: kolom sumber_data (dari mana titik berasal) + akurasi (seberapa tepat koordinatnya)
-- 2) berita_kejadian: berita (tautan) yang melengkapi sebuah titik kejadian, 1 titik bisa punya banyak berita
-- 3) catatan_tahun: catatan per tahun data (mis. "data simulasi"), ditampilkan sebagai peringatan di peta

ALTER TABLE titik_kejadian
    ADD COLUMN sumber_data VARCHAR(10) NOT NULL DEFAULT 'laporan' CHECK (sumber_data IN ('laporan', 'berita', 'simulasi')),
    ADD COLUMN akurasi     VARCHAR(10) NOT NULL DEFAULT 'tepat'   CHECK (akurasi IN ('tepat', 'desa', 'kecamatan'));
COMMENT ON COLUMN titik_kejadian.sumber_data IS 'laporan = laporan polisi/data resmi; berita = diambil dari pemberitaan media; simulasi = data contoh untuk pengembangan';
COMMENT ON COLUMN titik_kejadian.akurasi     IS 'tepat = koordinat TKP; desa/kecamatan = perkiraan di tingkat desa/kecamatan (mis. dari berita yang hanya menyebut wilayah)';

-- Semua titik yang sudah ada sebelum migrasi ini berasal dari CSV simulasi (titik_kejadian_2024_simulasi.csv),
-- jadi ditandai sebagai simulasi. Hapus baris UPDATE ini bila kamu sudah mengimpor titik dari data resmi.
UPDATE titik_kejadian SET sumber_data = 'simulasi', akurasi = 'kecamatan';
CREATE INDEX idx_titik_sumber ON titik_kejadian (sumber_data);

CREATE TABLE berita_kejadian (
    id_berita       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_titik        BIGINT NOT NULL REFERENCES titik_kejadian(id_titik) ON DELETE CASCADE,
    judul           VARCHAR(300) NOT NULL,                                   -- judul ringkas (ditulis ulang, bukan salinan teks berita)
    sumber          VARCHAR(100) NOT NULL,                                   -- nama media, mis. "ANTARA", "detikJabar"
    url             VARCHAR(2000) NOT NULL CHECK (url ~* '^https?://'),      -- hanya http/https (bukan javascript:)
    tanggal_terbit  DATE,
    ringkasan       VARCHAR(600),                                            -- ringkasan singkat dengan kalimat sendiri
    dibuat_pada     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id_titik, url)
);
COMMENT ON TABLE berita_kejadian IS 'Tautan berita yang melengkapi titik kejadian. Hanya metadata + ringkasan; isi artikel tidak disalin.';
CREATE INDEX idx_berita_titik ON berita_kejadian (id_titik);

CREATE TABLE catatan_tahun (
    tahun        SMALLINT PRIMARY KEY CHECK (tahun BETWEEN 2000 AND 2100),
    catatan      VARCHAR(500) NOT NULL,
    diubah_pada  TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE catatan_tahun IS 'Catatan per tahun (mis. status data simulasi / data parsial). Dibaca GET /api/tahun, diubah admin lewat PUT /api/tahun/{tahun}/catatan.';

-- Data 2025 dan 2026 yang disertakan di repo (data/simulasi/) adalah SIMULASI untuk pengembangan. Hapus catatan ini
-- (DELETE /api/tahun/{tahun}/catatan) setelah kamu mengganti dengan data resmi.
INSERT INTO catatan_tahun (tahun, catatan) VALUES
    (2025, 'Data tahun 2025 adalah SIMULASI untuk pengembangan, bukan data resmi kepolisian.'),
    (2026, 'Data tahun 2026 adalah SIMULASI untuk pengembangan (periode Januari-Oktober), bukan data resmi kepolisian.')
ON CONFLICT (tahun) DO NOTHING;
