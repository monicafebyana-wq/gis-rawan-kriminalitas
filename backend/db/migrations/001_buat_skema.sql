-- 001_buat_skema.sql
-- Skema database sesuai desain di slide (polsek, jenis_kejahatan, kasus_kejahatan, zona_kerawanan, pengguna).
-- Dijalankan lewat runner (backend/db/migrations/run.sh) dalam satu transaksi.

CREATE EXTENSION IF NOT EXISTS postgis;

-- ---------------------------------------------------------------
-- polsek: 1 baris per wilayah Polsek (+ poligon batas wilayah)
-- ---------------------------------------------------------------
CREATE TABLE polsek (
    id_polsek           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_polsek         VARCHAR(100) NOT NULL UNIQUE,
    nama_wilayah_resmi  VARCHAR(100),                          -- nama kecamatan untuk mencocokkan poligon (opsional)
    geom                geometry(MultiPolygon, 4326)           -- WGS 84; diisi saat impor GeoJSON (Polygon -> ST_Multi)
);
COMMENT ON TABLE  polsek      IS 'Wilayah Polsek beserta poligon batas wilayah';
COMMENT ON COLUMN polsek.geom IS 'MultiPolygon EPSG:4326. Nullable: data kasus bisa diimpor sebelum poligon tersedia';
CREATE INDEX idx_polsek_geom ON polsek USING GIST (geom);

-- ---------------------------------------------------------------
-- jenis_kejahatan: 18 jenis
-- ---------------------------------------------------------------
CREATE TABLE jenis_kejahatan (
    id_jenis    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_jenis  VARCHAR(30)  NOT NULL UNIQUE,
    nama_jenis  VARCHAR(100) NOT NULL
);
COMMENT ON TABLE jenis_kejahatan IS 'Jenis kejahatan (mis. ANIAYA, CURAT, CURANMOR_R2)';

-- ---------------------------------------------------------------
-- kasus_kejahatan: jumlah kasus per Polsek x jenis x tahun
-- ---------------------------------------------------------------
CREATE TABLE kasus_kejahatan (
    id_kasus    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_polsek   INTEGER  NOT NULL REFERENCES polsek(id_polsek)          ON UPDATE CASCADE ON DELETE RESTRICT,
    id_jenis    INTEGER  NOT NULL REFERENCES jenis_kejahatan(id_jenis)  ON UPDATE CASCADE ON DELETE RESTRICT,
    tahun       SMALLINT NOT NULL CHECK (tahun BETWEEN 2000 AND 2100),
    jumlah      INTEGER  NOT NULL DEFAULT 0 CHECK (jumlah >= 0),
    CONSTRAINT uq_kasus_polsek_jenis_tahun UNIQUE (id_polsek, id_jenis, tahun)
);
COMMENT ON TABLE kasus_kejahatan IS 'Rekap jumlah kasus; kombinasi (polsek, jenis, tahun) unik';
CREATE INDEX idx_kasus_tahun ON kasus_kejahatan (tahun);
CREATE INDEX idx_kasus_jenis ON kasus_kejahatan (id_jenis);
-- (id_polsek, ...) sudah tercakup oleh indeks unik uq_kasus_polsek_jenis_tahun

-- ---------------------------------------------------------------
-- zona_kerawanan: hasil klasifikasi zona per Polsek per tahun
-- (diisi otomatis oleh fungsi refresh_zona_kerawanan() di migrasi 002)
-- ---------------------------------------------------------------
CREATE TABLE zona_kerawanan (
    id_zona         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_polsek       INTEGER     NOT NULL REFERENCES polsek(id_polsek) ON UPDATE CASCADE ON DELETE CASCADE,
    tahun           SMALLINT    NOT NULL CHECK (tahun BETWEEN 2000 AND 2100),
    total_kasus     INTEGER     NOT NULL CHECK (total_kasus >= 0),
    kategori_zona   VARCHAR(10) NOT NULL CHECK (kategori_zona IN ('tinggi', 'sedang', 'rendah')),
    CONSTRAINT uq_zona_polsek_tahun UNIQUE (id_polsek, tahun)
);
COMMENT ON TABLE zona_kerawanan IS 'Zona kerawanan per Polsek per tahun (tinggi >=60, sedang 30-59, rendah <30)';
CREATE INDEX idx_zona_tahun_kategori ON zona_kerawanan (tahun, kategori_zona);

-- ---------------------------------------------------------------
-- pengguna: khusus login admin/operator (tidak berelasi)
-- ---------------------------------------------------------------
CREATE TABLE pengguna (
    id_pengguna    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    peran          VARCHAR(10)  NOT NULL CHECK (peran IN ('admin', 'operator'))
);
COMMENT ON TABLE pengguna IS 'Akun admin/operator. Simpan HANYA hash password (bcrypt), jangan plaintext';
